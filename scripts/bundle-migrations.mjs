// Inlines drizzle/*.sql (in journal order) into lib/db/migrations.generated.ts so the
// migration runner works on any host, IIS included, and in tests without reading the filesystem.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "drizzle";
const journal = JSON.parse(readFileSync(join(dir, "meta", "_journal.json"), "utf8"));
const entries = [...journal.entries]
  .sort((a, b) => a.idx - b.idx)
  .map((e) => ({ tag: e.tag, sql: readFileSync(join(dir, `${e.tag}.sql`), "utf8").replace(/\r\n/g, "\n") }));

const out = `// Generated by scripts/bundle-migrations.mjs from drizzle/*.sql — do not edit by hand.
// Regenerate with: npm run db:generate

export type Migration = { tag: string; sql: string };

export const MIGRATIONS: Migration[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(join("lib", "db", "migrations.generated.ts"), out);
console.log(`Bundled ${entries.length} migration(s) → lib/db/migrations.generated.ts`);
