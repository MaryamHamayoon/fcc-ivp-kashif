// Precomputes the compact country table from the `world-countries` package (dev dependency)
// so the runtime seed never bundles the 3.6 MB source JSON. Run: npm run data:countries
import { readFileSync, writeFileSync } from "node:fs";
import countries from "world-countries";
import { COUNTRY_NAME_OVERRIDES, EXCLUDED_COUNTRY_CODES, regionForCountry } from "../lib/domain/regions";

const version = (JSON.parse(readFileSync("node_modules/world-countries/package.json", "utf8")) as { version: string }).version;

const rows = countries
  .filter((c) => !EXCLUDED_COUNTRY_CODES.has(c.cca2) && c.region !== "Antarctic")
  .map((c) => [c.cca2, c.cca3, c.ccn3, COUNTRY_NAME_OVERRIDES[c.cca2] ?? c.name.common, regionForCountry(c), c.latlng[0], c.latlng[1]] as const)
  .sort((a, b) => a[3].localeCompare(b[3], "en"));

const out = `// Generated by scripts/build-countries.ts from world-countries ${version} — do not edit by hand.
// Regenerate with: npm run data:countries
import type { RegionId } from "../../../lib/domain/regions";

export type CountryTuple = readonly [cca2: string, cca3: string, ccn3: string, name: string, regionId: RegionId, lat: number, lng: number];

export const COUNTRY_DATA: readonly CountryTuple[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];
`;

writeFileSync("db/seed/fixtures/countries.generated.ts", out);
console.log(`Wrote ${rows.length} countries → db/seed/fixtures/countries.generated.ts`);
